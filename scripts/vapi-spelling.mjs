#!/usr/bin/env node
/**
 * PUT THE STUDIO SPELLING STANDARD ON EVERY VOICE AGENT.
 *
 *   node scripts/vapi-spelling.mjs                 # what would change, live vs standard
 *   node scripts/vapi-spelling.mjs --apply         # write it to every live agent
 *   node scripts/vapi-spelling.mjs --apply --only hall-roofing-concierge-bonifay
 *
 * Sarah, 2026-08-17: "lets implement that way of saying the word with the
 * letter, lets do that for all of our voice agents, its needed for everyone."
 *
 * WHAT IT DOES
 * Appends (or replaces) ONE section in each agent's system prompt: the text in
 * vapi/spelling-standard.md. Nothing else moves. The patch carries only
 * `model`, rebuilt from the LIVE model object with a new system message, so
 * tools, voice, transcriber, temperature, webhook and every call-handling plan
 * are untouched by construction rather than by care.
 *
 * IDEMPOTENT. The block starts with a sentinel line carrying a version. A
 * second run with the same version is a no-op; editing the standard and
 * bumping the version rewrites the block in place instead of stacking a second
 * copy. That is what makes this safe to run from CI later.
 *
 * ⚠️ MR. MUSTARD IS EXCLUDED ON PURPOSE. His prompt is generated by
 * scripts/setup-vapi-mustard.mjs, which owns a longer version of these same
 * rules. If this script wrote to him, the next `--update` from that script
 * would silently drop it again. Change his rules there.
 *
 * ⚠️ IT NEVER WRITES A SECRET. Tool-level `server` blocks come back from Vapi
 * with their secrets in full (see vapi/README.md). They are read into memory,
 * PATCHed straight back unchanged, and never printed and never written to a
 * repo file. The snapshot writer below only touches the system message.
 *
 * Needs VAPI_API_KEY (the PRIVATE key) in process.env, ./.env.local, or the
 * voice-agent project's .env.
 */

import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const CONFIG_DIR = resolve(__dirname, '../vapi/assistants');
const STANDARD = resolve(__dirname, '../vapi/spelling-standard.md');

const APPLY = process.argv.includes('--apply');
const onlyIdx = process.argv.indexOf('--only');
const ONLY = onlyIdx > -1 ? process.argv[onlyIdx + 1] : null;

/** His prompt is generated elsewhere; see the header. */
const EXCLUDE = new Set(['Mr. Mustard']);

/* ─────────────────────────── credentials ─────────────────────────── */

function loadEnvFile(path) {
  try {
    const out = {};
    for (const line of readFileSync(path, 'utf8').split(/\r?\n/)) {
      const m = /^([A-Z0-9_]+)\s*=\s*(.*)$/.exec(line.trim());
      if (m) out[m[1]] = m[2].replace(/^["']|["']$/g, '');
    }
    return out;
  } catch {
    return {};
  }
}
const fileEnv = {
  ...loadEnvFile(resolve(__dirname, '../../modern-mustard-seed-voice-agent/.env')),
  ...loadEnvFile(resolve(__dirname, '../.env.local')),
};
const real = (v) => (v && !/^\[SENSITIVE\]$/i.test(v) ? v : '');
const KEY = real(process.env.VAPI_API_KEY) || real(fileEnv.VAPI_API_KEY) || real(fileEnv.VAPI_PRIVATE_KEY);
if (!KEY) {
  console.error('\nMissing VAPI_API_KEY (the PRIVATE key). Nothing was contacted.\n');
  process.exitCode = 1;
}

/* ─────────────────────────── the standard ─────────────────────────── */

if (!existsSync(STANDARD)) {
  console.error(`\nMissing ${STANDARD}\n`);
  process.exitCode = 1;
}

const doc = readFileSync(STANDARD, 'utf8');
const start = doc.indexOf('# Letters, numbers and addresses, out loud');
if (start === -1) {
  console.error('\nvapi/spelling-standard.md has no installable block. Its first line must start with "# Letters, numbers and addresses, out loud".\n');
  process.exitCode = 1;
}
const BLOCK = doc.slice(start).trim();
const SENTINEL = BLOCK.split('\n')[0]; // carries the version, e.g. "(studio standard v1)"
const SENTINEL_ANY = /^# Letters, numbers and addresses, out loud.*$/m;

/**
 * Replace an existing installed block (any version) or append a new one. A
 * block runs from its sentinel line to the next top-level heading, so a prompt
 * that already ends with it and a prompt that has sections after it both work.
 */
function install(prompt) {
  const m = SENTINEL_ANY.exec(prompt);
  if (!m) return `${prompt.trimEnd()}\n\n${BLOCK}\n`;
  const from = m.index;
  const after = prompt.slice(from + m[0].length);
  const nextHeading = after.search(/^# /m);
  const end = nextHeading === -1 ? prompt.length : from + m[0].length + nextHeading;
  return `${prompt.slice(0, from)}${BLOCK}\n\n${prompt.slice(end).trimStart()}`.trimEnd() + '\n';
}

/* ─────────────────────────── the fleet ─────────────────────────── */

const api = async (path, init = {}) => {
  const r = await fetch(`https://api.vapi.ai${path}`, {
    ...init,
    headers: { Authorization: `Bearer ${KEY}`, 'Content-Type': 'application/json', ...(init.headers || {}) },
  });
  return { status: r.status, body: await r.json().catch(() => ({})) };
};

const slugify = (name) =>
  String(name || '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');

const list = await api('/assistant?limit=100');
if (list.status !== 200) {
  console.error(`\nCould not list assistants (${list.status}). Nothing was changed.\n`);
  process.exitCode = 1;
}
const assistants = Array.isArray(list.body) ? list.body : [];

let changed = 0;
let already = 0;
let skipped = 0;

for (const a of assistants) {
  const name = a.name || '(unnamed)';
  const messages = a.model?.messages ?? [];
  const sysIdx = messages.findIndex((m) => m.role === 'system');
  const prompt = sysIdx > -1 ? String(messages[sysIdx].content ?? '') : '';

  // The six __probe / __voiceprobe artifacts left over from voice sampling are
  // not agents. Name check as well as prompt length, because a probe that got
  // a throwaway prompt during a model-enum test still is not an agent.
  if (!prompt.trim() || /^__(probe|voiceprobe)/i.test(name)) {
    skipped++;
    continue;
  }
  if (EXCLUDE.has(name)) {
    console.log(`${name.padEnd(38)} skipped, his prompt is generated by setup-vapi-mustard.mjs`);
    skipped++;
    continue;
  }
  if (ONLY && slugify(name) !== ONLY) continue;

  if (prompt.includes(SENTINEL)) {
    console.log(`${name.padEnd(38)} already current`);
    already++;
    continue;
  }

  const next = install(prompt);
  const delta = next.length - prompt.length;
  const verb = SENTINEL_ANY.test(prompt) ? 'REPLACE older version' : 'ADD';
  console.log(`${name.padEnd(38)} ${verb.padEnd(22)} ${prompt.length} -> ${next.length} chars (${delta >= 0 ? '+' : ''}${delta})`);

  if (!APPLY) {
    changed++;
    continue;
  }

  // Rebuild the model object from LIVE, swapping only the system message, so
  // tools (and the per-tool server secrets Vapi returns in full) ride back
  // unchanged. Everything outside `model` is not in the patch at all.
  const model = { ...a.model, messages: messages.map((m, i) => (i === sysIdx ? { ...m, content: next } : m)) };
  const res = await api(`/assistant/${a.id}`, { method: 'PATCH', body: JSON.stringify({ model }) });
  if (res.status !== 200) {
    console.log(`  PATCH FAILED ${res.status}: ${JSON.stringify(res.body?.message ?? res.body).slice(0, 160)}`);
    continue;
  }

  // Verify from the server rather than trusting the 200, then mirror into the
  // repo snapshot if this agent is tracked.
  const after = await api(`/assistant/${a.id}`);
  const live = String((after.body.model?.messages ?? []).find((m) => m.role === 'system')?.content ?? '');
  const toolsBefore = (a.model?.tools ?? []).length;
  const toolsAfter = (after.body.model?.tools ?? []).length;
  const ok = live.includes(SENTINEL) && toolsBefore === toolsAfter;
  console.log(`  ${ok ? 'applied' : 'APPLIED BUT VERIFY FAILED'}, ${live.length} chars live, tools ${toolsBefore} -> ${toolsAfter}`);
  if (ok) changed++;

  const path = join(CONFIG_DIR, `${slugify(name)}.json`);
  if (existsSync(path)) {
    try {
      const cfg = JSON.parse(readFileSync(path, 'utf8'));
      const msgs = cfg.model?.messages ?? [];
      const i = msgs.findIndex((m) => m.role === 'system');
      if (i > -1) {
        msgs[i].content = live;
        writeFileSync(path, JSON.stringify(cfg, null, 2) + '\n');
        console.log(`  snapshot updated: vapi/assistants/${slugify(name)}.json`);
      }
    } catch (err) {
      console.log(`  snapshot NOT updated (${err instanceof Error ? err.message : 'unreadable'})`);
    }
  }
}

console.log(
  `\n${APPLY ? 'Applied to' : 'Would change'} ${changed} agent(s). ${already} already current, ${skipped} skipped.` +
    (APPLY ? '' : '\nRun again with --apply to write it.')
);
if (!APPLY && changed) console.log('Review vapi/spelling-standard.md first: that file is the text.\n');

// Windows: process.exit() mid-fetch trips a libuv assertion and returns 127.
process.exitCode = 0;
